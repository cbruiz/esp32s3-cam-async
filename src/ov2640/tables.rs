//! OV2640 register initialisation tables.
//!
//! Each table is a `&[(reg, val)]` slice fed to [`write_regs`](super::write_regs).
//! The tables are applied in two phases during sensor init:
//!
//! 1. [`OV2640_SETTINGS_CIF`] — common base configuration (sensor bank +
//!    DSP bank). Enables AGC/AEC/banding-filter and leaves the output format
//!    in YUV422. Applied after a soft-reset, before any resolution-specific
//!    overrides.
//!
//! 2. [`OV2640_SETTINGS_TO_SVGA`] — switches the sensor window to SVGA
//!    (800 × 600). Applied as part of the QVGA scaling sequence because SVGA
//!    gives a clean 2.5× down-scale ratio to 320 × 240, whereas CIF would
//!    require an awkward 1.25× ratio.
//!
//! ## Table format
//!
//! Entries are `(register_address, value)` pairs. A `(BANK_SEL, BANK_*)` pair
//! anywhere in a table switches the active register bank for all subsequent
//! entries in that table.

use super::registers::*;

