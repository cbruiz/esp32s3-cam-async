/// SVGA (800 × 600) sensor-window configuration, used as the scaling base for
/// QVGA (320 × 240) output.
///
/// Applied inside `set_window` after
/// [`OV2640_SETTINGS_CIF`], before the DSP zoom/crop registers are written.
///
/// **Why SVGA instead of CIF?**
/// SVGA → QVGA is a clean 2.5× down-scale (800 / 320 = 2.5, 600 / 240 = 2.5),
/// which the hardware DCW + scaler handles without rounding artefacts.
/// CIF (352 × 288) → QVGA would require a 1.1× scale, producing visible
/// aliasing.
///
/// The table ends with the DSP scaling registers pre-loaded for SVGA input
/// (`HSIZE8 = 0x64`, `VSIZE8 = 0x4B`) and `CTRL2 = 0x3D` which enables the
/// DCW path (800 → 400, 600 → 300) in preparation for the final zoom step
/// (400 → 320, 300 → 240).
pub const OV2640_SETTINGS_TO_SVGA: &[(u8, u8)] = &[
    (BANK_SEL, BANK_SENSOR),
    (COM7, COM7_RES_SVGA),
    (COM1, 0x0A),
    (REG32, 0x09),
    (HSTART, 0x11), (HSTOP, 0x43),
    (VSTART, 0x00), (VSTOP, 0x4B),
    (BD50, 0xca), (BD60, 0xa8),
    (0x5a, 0x23), (0x6d, 0x00), (0x3d, 0x38),
    (0x39, 0x92), (0x35, 0xda), (0x22, 0x1a),
    (0x37, 0xc3), (0x23, 0x00),
    (ARCOM2, 0xc0), (0x06, 0x88), (0x07, 0xc0),
    (COM4, 0x87), (0x0e, 0x41), (0x4c, 0x00),
    (BANK_SEL, BANK_DSP),
    (RESET, RESET_DVP),
    // HSIZE8 = sensor_H/8 = 800/8 = 100 = 0x64
    // VSIZE8 = sensor_V/8 = 600/8 =  75 = 0x4B
    (HSIZE8, 0x64), (VSIZE8, 0x4B), (SIZEL, 0x00),
    (HSIZE, 0xC8), (VSIZE, 0x96),
    (XOFFL, 0x00), (YOFFL, 0x00),
    (VHYX, 0x00), (TEST, 0x00),
    // CTRL2 = 0x3D: DCW (800→400, 600→300) + scaler (400→320, 300→240).
    (CTRL2, 0x3D),
    // CTRLI bit 7 (LP_DP) enables the scaler's line-processing/downsize path.
    // esp32-camera sets it in every window table; with it cleared, the 2.5×
    // downscale shears the luma (stride) and misaligns the 4:2:0 chroma (green).
    (CTRLI, CTRLI_LP_DP),
];

